import AaronUI
import SwiftUI

/// Shared semantic roles from AaronUI, including its light and dark palettes.
enum SettingsAppearance {
    static let canvas = AUIColor.canvasRecessed
    static let surface = AUIColor.surface
    static let field = AUIColor.surfaceField
    static let line = AUIColor.lineDefault
    static let accent = AUIColor.accent
    static let ink = AUIColor.onSurface
    static let muted = AUIColor.onSurfaceMuted
}
